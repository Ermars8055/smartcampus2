import { useState, useEffect, useRef } from 'react';
import {
  Box, Typography, Card, Table, TableHead, TableBody, TableRow, TableCell,
  TableContainer, Button, Grid, FormControl, InputLabel, Select, MenuItem,
  TextField, FormControlLabel, Switch, CircularProgress, Paper, Divider, Stack, TablePagination
} from '@mui/material';
import {
  Search, Assessment, FileDownload, PictureAsPdf, Print, Refresh, Inventory2
} from '@mui/icons-material';
import dayjs from 'dayjs';
import ExcelJS from 'exceljs';
import { saveAs } from 'file-saver';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import api from '../services/api';
import { useMessage } from '../context/MessageContext';
import { useAuth } from '../context/AuthContext';

export default function EquipmentCountReport() {
  const { showMessage } = useMessage();
  const { user } = useAuth();
  
  const [categories, setCategories] = useState([]);
  const [institutions, setInstitutions] = useState([]);
  const [vendors, setVendors] = useState([]);
  
  const [loading, setLoading] = useState(false);
  const [data, setData] = useState([]);
  const [page, setPage] = useState(0);
  const [rowsPerPage, setRowsPerPage] = useState(10);
  
  const [filters, setFilters] = useState({
    institutionId: '',
    categoryId: '',
    vendorId: '',
    status: '',
    search: '',
    includeZero: false
  });

  const reportRef = useRef(null);

  useEffect(() => {
    api.get('/api/categories').then(r => setCategories(r.data)).catch(() => {});
    api.get('/api/institutions').then(r => setInstitutions(r.data)).catch(() => {});
    api.get('/api/vendors').then(r => setVendors(r.data)).catch(() => {});
  }, []);

  const fetchReport = async () => {
    setLoading(true);
    try {
      const params = {};
      if (filters.institutionId) params.institution_id = filters.institutionId;
      if (filters.categoryId) params.category_id = filters.categoryId;
      if (filters.vendorId) params.vendor_id = filters.vendorId;
      if (filters.status) params.status = filters.status;
      if (filters.search) params.search = filters.search;
      if (filters.includeZero) params.include_zero = true;

      const res = await api.get('/api/equipment/reports/count', { params });
      setData(res.data || []);
      setPage(0);
    } catch (err) {
      console.error(err);
      showMessage('Failed to load equipment count report data', 'Error', 'error');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchReport();
  }, []);

  const handleReset = () => {
    setFilters({
      institutionId: '',
      categoryId: '',
      vendorId: '',
      status: '',
      search: '',
      includeZero: false
    });
  };

  const totalCount = data.reduce((sum, item) => sum + (item.count || 0), 0);

  // Print Handler
  const handlePrint = () => {
    window.print();
  };

  // Export Excel
  const exportExcel = async () => {
    if (!data.length) {
      showMessage('No data available to export', 'Warning', 'warning');
      return;
    }

    const workbook = new ExcelJS.Workbook();
    const worksheet = workbook.addWorksheet('Equipment Count Report');

    // Title & Header Block
    worksheet.mergeCells('A1:C1');
    const titleCell = worksheet.getCell('A1');
    titleCell.value = 'EASTPOINT SMART CAMPUS';
    titleCell.font = { name: 'Arial', size: 14, bold: true, color: { argb: 'FF1E293B' } };
    titleCell.alignment = { horizontal: 'center' };

    worksheet.mergeCells('A2:C2');
    const subtitleCell = worksheet.getCell('A2');
    subtitleCell.value = 'EQUIPMENT COUNT REPORT';
    subtitleCell.font = { name: 'Arial', size: 12, bold: true, color: { argb: 'FF0284C7' } };
    subtitleCell.alignment = { horizontal: 'center' };

    worksheet.mergeCells('A3:C3');
    const metaCell = worksheet.getCell('A3');
    metaCell.value = `Generated On: ${dayjs().format('DD-MMM-YYYY HH:mm')} | Total Equipment: ${totalCount} | Generated By: ${user?.full_name || 'System'}`;
    metaCell.font = { name: 'Arial', size: 9, italic: true, color: { argb: 'FF64748B' } };
    metaCell.alignment = { horizontal: 'center' };

    worksheet.addRow([]);

    // Table Header
    const headerRow = worksheet.addRow(['Sl. No', 'Equipment name', 'Count']);
    headerRow.eachCell((cell) => {
      cell.font = { name: 'Arial', size: 11, bold: true, color: { argb: 'FFFFFFFF' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1E293B' } };
      cell.alignment = { vertical: 'middle', horizontal: cell.col === 3 ? 'right' : cell.col === 1 ? 'center' : 'left' };
      cell.border = {
        top: { style: 'thin', color: { argb: 'FF000000' } },
        bottom: { style: 'thin', color: { argb: 'FF000000' } },
        left: { style: 'thin', color: { argb: 'FF000000' } },
        right: { style: 'thin', color: { argb: 'FF000000' } }
      };
    });

    // Table Rows
    data.forEach((item, idx) => {
      const row = worksheet.addRow([idx + 1, item.equipment_name, item.count]);
      row.eachCell((cell, colNumber) => {
        cell.font = { name: 'Arial', size: 10 };
        cell.alignment = { vertical: 'middle', horizontal: colNumber === 3 ? 'right' : colNumber === 1 ? 'center' : 'left' };
        cell.border = {
          top: { style: 'thin', color: { argb: 'FFD1D5DB' } },
          bottom: { style: 'thin', color: { argb: 'FFD1D5DB' } },
          left: { style: 'thin', color: { argb: 'FFD1D5DB' } },
          right: { style: 'thin', color: { argb: 'FFD1D5DB' } }
        };
      });
    });

    // Total Row
    const totalRow = worksheet.addRow(['', 'Total', totalCount]);
    totalRow.eachCell((cell, colNumber) => {
      cell.font = { name: 'Arial', size: 11, bold: true, color: { argb: 'FF0F172A' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF1F5F9' } };
      cell.alignment = { vertical: 'middle', horizontal: colNumber === 3 ? 'right' : 'left' };
      cell.border = {
        top: { style: 'medium', color: { argb: 'FF000000' } },
        bottom: { style: 'medium', color: { argb: 'FF000000' } },
        left: { style: 'thin', color: { argb: 'FF000000' } },
        right: { style: 'thin', color: { argb: 'FF000000' } }
      };
    });

    // Column Widths
    worksheet.getColumn(1).width = 10;
    worksheet.getColumn(2).width = 45;
    worksheet.getColumn(3).width = 15;

    const buffer = await workbook.xlsx.writeBuffer();
    saveAs(new Blob([buffer]), `Equipment_Count_Report_${dayjs().format('YYYYMMDD')}.xlsx`);
  };

  // Export PDF
  const exportPDF = () => {
    if (!data.length) {
      showMessage('No data available to export', 'Warning', 'warning');
      return;
    }

    const doc = new jsPDF('p', 'mm', 'a4');
    
    // Header Block
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(30, 41, 59);
    doc.text('EASTPOINT SMART CAMPUS', 105, 15, { align: 'center' });

    doc.setFontSize(12);
    doc.setTextColor(2, 132, 199);
    doc.text('EQUIPMENT COUNT REPORT', 105, 22, { align: 'center' });

    doc.setFont('helvetica', 'italic');
    doc.setFontSize(9);
    doc.setTextColor(100, 116, 139);
    doc.text(`Generated On: ${dayjs().format('DD-MMM-YYYY HH:mm')} | Total Equipment: ${totalCount} | Generated By: ${user?.full_name || 'System'}`, 105, 28, { align: 'center' });

    doc.setLineWidth(0.5);
    doc.setDrawColor(203, 213, 225);
    doc.line(14, 32, 196, 32);

    // Table Data
    const tableBody = data.map((item, idx) => [
      idx + 1,
      item.equipment_name,
      item.count
    ]);

    tableBody.push([
      '',
      { content: 'Total', styles: { fontStyle: 'bold' } },
      { content: totalCount.toString(), styles: { fontStyle: 'bold', halign: 'right' } }
    ]);

    autoTable(doc, {
      startY: 36,
      head: [['Sl. No', 'Equipment name', 'Count']],
      body: tableBody,
      theme: 'grid',
      headStyles: {
        fillColor: [30, 41, 59],
        textColor: [255, 255, 255],
        fontStyle: 'bold',
        fontSize: 10,
        halign: 'left'
      },
      columnStyles: {
        0: { cellWidth: 20, halign: 'center' },
        1: { halign: 'left' },
        2: { cellWidth: 30, halign: 'right' }
      },
      styles: {
        fontSize: 9,
        cellPadding: 3
      },
      didParseCell: (dataCell) => {
        if (dataCell.section === 'head' && dataCell.column.index === 2) {
          dataCell.cell.styles.halign = 'right';
        }
        if (dataCell.section === 'head' && dataCell.column.index === 0) {
          dataCell.cell.styles.halign = 'center';
        }
      }
    });

    doc.save(`Equipment_Count_Report_${dayjs().format('YYYYMMDD')}.pdf`);
  };

  // Export CSV
  const exportCSV = () => {
    if (!data.length) return;
    const csvRows = [
      'Sl. No,Equipment name,Count',
      ...data.map((item, idx) => `"${idx + 1}","${item.equipment_name.replace(/"/g, '""')}","${item.count}"`),
      `"",Total,"${totalCount}"`
    ];
    const blob = new Blob([csvRows.join('\n')], { type: 'text/csv;charset=utf-8;' });
    saveAs(blob, `Equipment_Count_Report_${dayjs().format('YYYYMMDD')}.csv`);
  };

  return (
    <Box sx={{ p: { xs: 1, md: 3 }, maxWidth: 1200, margin: '0 auto' }}>
      {/* Print-specific Styling */}
      <style>
        {`
          @media print {
            body * {
              visibility: hidden;
            }
            #printable-report, #printable-report * {
              visibility: visible;
            }
            #printable-report {
              position: absolute;
              left: 0;
              top: 0;
              width: 100%;
              padding: 0;
              margin: 0;
              box-shadow: none !important;
            }
            .no-print {
              display: none !important;
            }
            .print-table {
              border-collapse: collapse !important;
              width: 100% !important;
            }
            .print-table th, .print-table td {
              border: 1px solid #000 !important;
              padding: 6px 10px !important;
              color: #000 !important;
            }
            .print-header {
              display: block !important;
              text-align: center;
              margin-bottom: 20px;
            }
          }
        `}
      </style>

      {/* Header Bar */}
      <Box className="no-print" sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 3, flexWrap: 'wrap', gap: 2 }}>
        <Box>
          <Typography variant="h5" sx={{ fontWeight: 800, color: '#0F172A', display: 'flex', alignItems: 'center', gap: 1 }}>
            <Assessment sx={{ color: '#0284C7' }} /> Equipment Count Report
          </Typography>
          <Typography variant="body2" sx={{ color: '#64748B' }}>
            Equipment stock totals by type and material classification
          </Typography>
        </Box>

        <Stack direction="row" spacing={1} flexWrap="wrap" gap={1}>
          <Button
            variant="outlined"
            color="primary"
            startIcon={<Print />}
            onClick={handlePrint}
            sx={{ borderRadius: 2, textTransform: 'none', fontWeight: 600 }}
          >
            Print
          </Button>
          <Button
            variant="outlined"
            color="error"
            startIcon={<PictureAsPdf />}
            onClick={exportPDF}
            sx={{ borderRadius: 2, textTransform: 'none', fontWeight: 600 }}
          >
            Export PDF
          </Button>
          <Button
            variant="outlined"
            color="success"
            startIcon={<FileDownload />}
            onClick={exportExcel}
            sx={{ borderRadius: 2, textTransform: 'none', fontWeight: 600 }}
          >
            Export Excel
          </Button>
          <Button
            variant="contained"
            startIcon={<FileDownload />}
            onClick={exportCSV}
            sx={{ borderRadius: 2, textTransform: 'none', fontWeight: 600, bgcolor: '#0F172A', '&:hover': { bgcolor: '#1E293B' } }}
          >
            CSV
          </Button>
        </Stack>
      </Box>

      {/* Filter Section */}
      <Card className="no-print" sx={{ p: 2.5, mb: 3, borderRadius: 3, boxShadow: '0 2px 8px rgba(0,0,0,0.04)' }}>
        <Grid container spacing={2} alignItems="center">
          <Grid item xs={12} sm={6} md={3}>
            <FormControl fullWidth size="small">
              <InputLabel shrink>Institution</InputLabel>
              <Select displayEmpty
                value={filters.institutionId}
                label="Institution"
                onChange={(e) => setFilters({ ...filters, institutionId: e.target.value })}
              >
                <MenuItem value="">All Institutions</MenuItem>
                {institutions.map((i) => (
                  <MenuItem key={i.id} value={i.id}>{i.name}</MenuItem>
                ))}
              </Select>
            </FormControl>
          </Grid>

          <Grid item xs={12} sm={6} md={3}>
            <FormControl fullWidth size="small">
              <InputLabel shrink>Category</InputLabel>
              <Select displayEmpty
                value={filters.categoryId}
                label="Category"
                onChange={(e) => setFilters({ ...filters, categoryId: e.target.value })}
              >
                <MenuItem value="">All Categories</MenuItem>
                {categories.map((c) => (
                  <MenuItem key={c.id} value={c.id}>{c.name}</MenuItem>
                ))}
              </Select>
            </FormControl>
          </Grid>

          <Grid item xs={12} sm={6} md={2}>
            <FormControl fullWidth size="small">
              <InputLabel shrink>Status</InputLabel>
              <Select displayEmpty
                value={filters.status}
                label="Status"
                onChange={(e) => setFilters({ ...filters, status: e.target.value })}
              >
                <MenuItem value="">All Statuses</MenuItem>
                <MenuItem value="In Store">In Store</MenuItem>
                <MenuItem value="Operational">Operational</MenuItem>
                <MenuItem value="Pending Installation">Pending Installation</MenuItem>
                <MenuItem value="Written Off">Written Off</MenuItem>
              </Select>
            </FormControl>
          </Grid>

          <Grid item xs={12} sm={6} md={4}>
            <TextField
              fullWidth
              size="small"
              label="Search Equipment Name"
              placeholder="e.g. Ventilator, BP, Monitor..."
              value={filters.search}
              onChange={(e) => setFilters({ ...filters, search: e.target.value })}
              InputProps={{
                startAdornment: <Search sx={{ color: '#94A3B8', mr: 1, fontSize: 20 }} />
              }}
            />
          </Grid>

          <Grid item xs={12} sm={6} md={6}>
            <FormControlLabel
              control={
                <Switch
                  checked={filters.includeZero}
                  onChange={(e) => setFilters({ ...filters, includeZero: e.target.checked })}
                  color="primary"
                />
              }
              label={
                <Typography variant="body2" sx={{ color: '#475569', fontWeight: 500 }}>
                  Include equipment types with 0 count
                </Typography>
              }
            />
          </Grid>

          <Grid item xs={12} sm={6} md={6} sx={{ display: 'flex', justifyContent: 'flex-end', gap: 1 }}>
            <Button
              variant="contained"
              startIcon={<Assessment />}
              onClick={fetchReport}
              sx={{ borderRadius: 2, textTransform: 'none', fontWeight: 600, px: 3 }}
            >
              Generate Report
            </Button>
            <Button
              variant="outlined"
              color="inherit"
              startIcon={<Refresh />}
              onClick={handleReset}
              sx={{ borderRadius: 2, textTransform: 'none', fontWeight: 500 }}
            >
              Reset
            </Button>
          </Grid>
        </Grid>
      </Card>

      {/* KPI Cards */}
      <Grid className="no-print" container spacing={3} sx={{ mb: 3 }}>
        <Grid item xs={12} sm={6} md={4}>
          <Paper elevation={0} sx={{ p: 2.5, borderRadius: 3, bgcolor: '#EFF6FF', border: '1px solid #BFDBFE' }}>
            <Typography variant="caption" sx={{ color: '#1D4ED8', fontWeight: 700, letterSpacing: '0.05em' }}>
              TOTAL EQUIPMENT COUNT
            </Typography>
            <Typography variant="h3" sx={{ color: '#1E3A8A', fontWeight: 900, mt: 0.5 }}>
              {totalCount.toLocaleString('en-IN')}
            </Typography>
          </Paper>
        </Grid>

        <Grid item xs={12} sm={6} md={4}>
          <Paper elevation={0} sx={{ p: 2.5, borderRadius: 3, bgcolor: '#F0FDF4', border: '1px solid #BBF7D0' }}>
            <Typography variant="caption" sx={{ color: '#15803D', fontWeight: 700, letterSpacing: '0.05em' }}>
              EQUIPMENT CATEGORIES / TYPES
            </Typography>
            <Typography variant="h3" sx={{ color: '#166534', fontWeight: 900, mt: 0.5 }}>
              {data.length}
            </Typography>
          </Paper>
        </Grid>

        <Grid item xs={12} sm={6} md={4}>
          <Paper elevation={0} sx={{ p: 2.5, borderRadius: 3, bgcolor: '#F8FAFC', border: '1px solid #E2E8F0' }}>
            <Typography variant="caption" sx={{ color: '#475569', fontWeight: 700, letterSpacing: '0.05em' }}>
              REPORT GENERATED
            </Typography>
            <Typography variant="subtitle1" sx={{ color: '#0F172A', fontWeight: 700, mt: 1 }}>
              {dayjs().format('DD-MMM-YYYY HH:mm')}
            </Typography>
          </Paper>
        </Grid>
      </Grid>

      {/* Printable Report Container */}
      <Paper
        id="printable-report"
        ref={reportRef}
        elevation={0}
        sx={{
          borderRadius: 3,
          border: '1px solid #E2E8F0',
          overflow: 'hidden',
          bgcolor: '#FFFFFF',
          boxShadow: '0 4px 6px -1px rgba(0,0,0,0.05)'
        }}
      >
        {/* Printable Header Block */}
        <Box sx={{ p: 3, borderBottom: '2px solid #0F172A', bgcolor: '#FAFAFA' }}>
          <Typography variant="h6" sx={{ fontWeight: 800, color: '#0F172A', textAlign: 'center', letterSpacing: '0.05em' }}>
            EASTPOINT SMART CAMPUS
          </Typography>
          <Typography variant="subtitle1" sx={{ fontWeight: 700, color: '#0284C7', textAlign: 'center', mt: 0.5 }}>
            EQUIPMENT COUNT REPORT
          </Typography>
          <Typography variant="caption" sx={{ display: 'block', textAlign: 'center', color: '#64748B', mt: 0.5 }}>
            Date: {dayjs().format('DD-MMM-YYYY')} | Total Equipment: {totalCount} | Generated By: {user?.full_name || 'System'}
          </Typography>
        </Box>

        {loading ? (
          <Box sx={{ display: 'flex', justifyContent: 'center', py: 8 }}>
            <CircularProgress size={36} />
          </Box>
        ) : (
          <TableContainer>
            <Table className="print-table" sx={{ borderCollapse: 'collapse' }}>
              <TableHead sx={{ bgcolor: '#F8FAFC' }}>
                <TableRow sx={{ borderBottom: '2px solid #0F172A' }}>
                  <TableCell sx={{ fontWeight: 800, color: '#0F172A', width: 90, borderRight: '1px solid #E2E8F0', py: 1.5 }}>
                    Sl. No
                  </TableCell>
                  <TableCell sx={{ fontWeight: 800, color: '#0F172A', borderRight: '1px solid #E2E8F0', py: 1.5 }}>
                    Equipment name
                  </TableCell>
                  <TableCell align="right" sx={{ fontWeight: 800, color: '#0F172A', width: 120, py: 1.5 }}>
                    Count
                  </TableCell>
                </TableRow>
              </TableHead>
              <TableBody>
                {data.slice(page * rowsPerPage, page * rowsPerPage + rowsPerPage).map((row, index) => (
                  <TableRow key={index} hover sx={{ borderBottom: '1px solid #E2E8F0' }}>
                    <TableCell sx={{ fontWeight: 600, color: '#475569', borderRight: '1px solid #E2E8F0', py: 1 }}>
                      {page * rowsPerPage + index + 1}
                    </TableCell>
                    <TableCell sx={{ fontWeight: 600, color: '#1E293B', borderRight: '1px solid #E2E8F0', py: 1 }}>
                      {row.equipment_name}
                    </TableCell>
                    <TableCell align="right" sx={{ fontWeight: 800, color: '#0F172A', py: 1 }}>
                      {row.count}
                    </TableCell>
                  </TableRow>
                ))}

                {data.length === 0 && (
                  <TableRow>
                    <TableCell colSpan={3} align="center" sx={{ py: 4, color: '#94A3B8' }}>
                      No equipment records found matching the criteria.
                    </TableCell>
                  </TableRow>
                )}

                {/* Total Summary Row */}
                {data.length > 0 && (
                  <TableRow sx={{ bgcolor: '#F1F5F9', borderTop: '2px solid #0F172A' }}>
                    <TableCell sx={{ borderRight: '1px solid #E2E8F0', py: 1.5 }} />
                    <TableCell sx={{ fontWeight: 800, color: '#0F172A', fontSize: '1rem', borderRight: '1px solid #E2E8F0', py: 1.5 }}>
                      Total
                    </TableCell>
                    <TableCell align="right" sx={{ fontWeight: 900, color: '#0F172A', fontSize: '1.1rem', py: 1.5 }}>
                      {totalCount.toLocaleString('en-IN')}
                    </TableCell>
                  </TableRow>
                )}
              </TableBody>
            </Table>
          </TableContainer>
        )}
        
        <TablePagination
          className="no-print"
          rowsPerPageOptions={[10, 25, 50, 100]}
          component="div"
          count={data.length}
          rowsPerPage={rowsPerPage}
          page={page}
          onPageChange={(e, newPage) => setPage(newPage)}
          onRowsPerPageChange={(e) => {
            setRowsPerPage(parseInt(e.target.value, 10));
            setPage(0);
          }}
          sx={{ borderTop: '1px solid #E2E8F0', bgcolor: '#F8FAFC' }}
        />

        <Box className="no-print" sx={{ p: 2, borderTop: '1px solid #E2E8F0', bgcolor: '#F8FAFC', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
          <Typography variant="caption" sx={{ color: '#64748B', fontWeight: 500 }}>
            Showing {data.length} equipment categories
          </Typography>
          <Typography variant="caption" sx={{ color: '#64748B', fontWeight: 600 }}>
            Eastpoint Smart Campus | Equipment Management Module
          </Typography>
        </Box>
      </Paper>
    </Box>
  );
}
